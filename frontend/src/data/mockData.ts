// Función simple y simulada para detectar servicios potencialmente duplicados
// (HU6JA): mismo vehículo, mismo tipo de servicio, misma fecha o fecha muy cercana.
export function findPotentialDuplicates(records: MaintenanceRecord[]): MaintenanceRecord[][] {
  const groups = new Map<string, MaintenanceRecord[]>();
  for (const r of records) {
    const key = `${r.vehicleId}__${r.type}__${r.date}`;
    const arr = groups.get(key) ?? [];
    arr.push(r);
    groups.set(key, arr);
  }
  return Array.from(groups.values()).filter((group) => group.length > 1);
}
